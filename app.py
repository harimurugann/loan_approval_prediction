# FEATURE 2: Advanced Fraud Detection
def detect_fraud(income, amount, credit):
    # Rule 1: Loan amount should not be 10x of annual income
    # Rule 2: Low credit score with very high loan demand
    if amount > (income * 10) or (credit < 450 and amount > 500000):
        return True
    return False

# FEATURE 1: PDF Report Generator
def generate_pdf(name, income, credit, amount, res, prob):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(200, 10, txt="Loan Eligibility Assessment Report", ln=True, align='C')
    pdf.set_font("Arial", size=12)
    pdf.ln(10)
    pdf.cell(200, 10, txt=f"Applicant Name: {name}", ln=True)
    pdf.cell(200, 10, txt=f"Date: {datetime.date.today()}", ln=True)
    pdf.cell(200, 10, txt=f"Credit Score: {credit}", ln=True)
    pdf.cell(200, 10, txt=f"Loan Amount Requested: ${amount}", ln=True)
    pdf.cell(200, 10, txt=f"AI Prediction: {res}", ln=True)
    pdf.cell(200, 10, txt=f"Confidence Level: {prob}%", ln=True)
    pdf.ln(10)
    pdf.set_font("Arial", 'I', 10)
    pdf.cell(200, 10, txt="Generated by Hari Murugan's Loan Intelligence System", ln=True, align='C')
    return pdf.output(dest='S').encode('latin-1')

def log_user_data(name, income, credit, amount, result, prob):
    log_file = 'user_logs_production.csv'
    lat, lon = 13.0827, 80.2707 
    log_entry = pd.DataFrame({
        'Timestamp': [datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')],
        'Applicant_Name': [name], 'Annual_Income': [income], 'Credit_Score': [credit],
        'Loan_Amount': [amount], 'Prediction': [result], 'Probability_%': [prob],
        'lat': [lat], 'lon': [lon]
    })
    if not os.path.isfile(log_file): log_entry.to_csv(log_file, index=False)
    else: log_entry.to_csv(log_file, mode='a', header=False, index=False)

